// Copies the River Bridge adapter + the vendored kit files it needs into functions/src/vendor/river-bridge
// (git-ignored), adding `.js` to relative imports for NodeNext. Source of truth: packages/river-bridge.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const pkg = join(root, "packages/river-bridge");
const out = join(root, "functions/src/vendor/river-bridge");
const KIT_FILES = ["canonical", "sign", "verify", "nonce", "idempotency", "problems"];

const banner = "// GENERATED by functions/scripts/sync-bridge.mjs from packages/river-bridge. Do not edit.\n";
const addJs = (src, map) => src.replace(/(from\s+['"])(\.{1,2}\/[^'"]+)(['"])/g, (_m, a, spec, b) => `${a}${map(spec)}${b}`);

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, "kit"), { recursive: true });
for (const name of KIT_FILES) {
  const src = readFileSync(join(pkg, "kit/src", `${name}.ts`), "utf8");
  writeFileSync(join(out, "kit", `${name}.ts`), banner + addJs(src, (spec) => `${spec}.js`));
}
const index = readFileSync(join(pkg, "src/index.ts"), "utf8");
writeFileSync(join(out, "index.ts"), banner + addJs(index, (spec) => {
  const m = /^\.\.\/kit\/src\/(.+)$/.exec(spec);
  if (!m || !KIT_FILES.includes(m[1])) throw new Error(`sync-bridge: unexpected import ${spec}`);
  return `./kit/${m[1]}.js`;
}));
